/**
 * Where the database and the content live, resolved from this file rather than from
 * `process.cwd()` so a script, a test and `pnpm --filter` all agree wherever they are run from.
 */

import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The repository root: three directories up from `packages/db/src/`. */
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

/** The SQLite file. `DATABASE_URL` overrides it; `.gitignore` excludes `data/*.db`. */
export const DEFAULT_DB_PATH = process.env.DATABASE_URL ?? join(REPO_ROOT, 'data', 'app.db');

/** The seeded content tree and the saved situations beside it. */
export const CONTENT_DIR = join(REPO_ROOT, 'content');
export const SCENARIOS_DIR = join(REPO_ROOT, 'scenarios');

/** Committed migrations, generated by `drizzle-kit generate`. */
export const MIGRATIONS_DIR = join(REPO_ROOT, 'packages', 'db', 'drizzle');
